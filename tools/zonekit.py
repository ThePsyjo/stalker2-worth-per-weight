"""Package a text-override mod in the layout the Zone Kit produces for Steam Workshop.

The game mounts Workshop mods after it has loaded Game.locres, so a replaced locres is ignored there.
Zone Kit mods instead ship a ModLocalizationDatabaseDataAsset ("Autogenerated_<n>_LocalizationDatabase"),
which the game applies on top of the base texts. template/ holds the cooked boilerplate packages
(legacy .uasset/.uexp); this module writes the database export and converts everything with retoc.
"""
import os, shutil, struct, subprocess, time
from pathlib import Path

MOD = 'ValuePerKilo'  # plugin name; must stay 12 chars, the cooked template headers assume that length
DB_STEM = 'Autogenerated_1792500349_LocalizationDatabase'
PACKAGE_TAG = 0x9E2A83C1
# legacy header fields of the database package (fixed layout, see FINDINGS.md)
OFF_BULK_START, OFF_EXPORT_SIZE, OFF_EXPORT_OFFSET = 0xEC, 0x5A7, 0x5AF

# name-map index of each ELocalizationLanguage value in the database package -> locres culture
LANG_INDEX = {'ar': 0, 'zh-Hans': 1, 'zh-Hant': 2, 'cs': 3, 'en': 4, 'fr': 5, 'de': 6, 'it': 7, 'ja': 8,
              'ko': 9, 'pl': 10, 'pt-BR': 11, 'ru': 12, 'sr': 13, 'es': 14, 'es-419': 15, 'tr': 16, 'uk': 17}


def _fstr(s):
    if not s:
        return struct.pack('<i', 0)
    if all(ord(c) < 128 for c in s):
        b = s.encode('ascii') + b'\0'
        return struct.pack('<i', len(b)) + b
    b = s.encode('utf-16-le') + b'\0\0'
    return struct.pack('<i', -(len(b) // 2)) + b


def db_export(entries):
    """entries: {text key: {culture: text}} -> serialized export (unversioned TMap<FString, {TMap<lang, FString>}>)."""
    out = bytearray(struct.pack('<Hii', 0x0300, 0, len(entries)))
    for key, texts in entries.items():
        langs = [(LANG_INDEX[c], t) for c, t in texts.items() if c in LANG_INDEX]
        out += _fstr(key) + struct.pack('<Hii', 0x0300, 0, len(langs))
        for idx, text in sorted(langs):
            out += struct.pack('<II', idx, 0) + _fstr(text)
    out += b'\0\0\0\0'  # end of object serialization, as in Zone Kit output
    return bytes(out)


def _write_db(stage, entries):
    content = stage / 'Stalker2' / 'Content'
    uasset = bytearray((content / f'{DB_STEM}.uasset').read_bytes())
    export = db_export(entries)
    header = len(uasset)
    assert struct.unpack_from('<q', uasset, OFF_EXPORT_OFFSET)[0] == header, 'template layout changed'
    struct.pack_into('<q', uasset, OFF_EXPORT_SIZE, len(export))
    struct.pack_into('<q', uasset, OFF_BULK_START, header + len(export))
    (content / f'{DB_STEM}.uasset').write_bytes(uasset)
    (content / f'{DB_STEM}.uexp').write_bytes(export + struct.pack('<I', PACKAGE_TAG))


def _manifest(path, files):
    stamp = time.strftime('%Y-%m-%dT%H:%M:%S.000Z', time.gmtime())
    path.write_text(''.join(f'{f}\t{stamp}\r\n' for f in files), encoding='utf-8')


def _add_cooked(stage, cooked):
    """Place assets cooked by the stub project (ue/Stalker2, plugin /<Mod>/) into the staging tree.

    *_WorldSubsystemData goes to OverrideContent (/Game/ on disk, redirected to /<Mod>/ like the text database);
    its class lives in the game's /Script/Engine, stubbed as the same-length /Script/WPWEng.
    """
    for f in sorted(Path(cooked).glob('*.uasset')) + sorted(Path(cooked).glob('*.uexp')):
        data = f.read_bytes()
        if '_WorldSubsystemData' in f.name:
            dst = stage / 'Stalker2/Content' / f.name
            data = data.replace(b'/Script/WPWEng', b'/Script/Engine')
        else:
            dst = stage / f'Stalker2/Mods/{MOD}/Content' / f.name
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)


def package(entries, patches, template, out, retoc, repak, tmp, cooked=None):
    """Write the Workshop content folder to out (replaced if it exists).

    entries: text database {key: {culture: text}} (empty: no database); patches: cfg patch files
    {path under GameLite/: text}; cooked: folder with cooked plugin assets from tools/build_bp.sh.
    """
    stage = Path(tmp) / 'zk'
    shutil.rmtree(stage, ignore_errors=True)
    shutil.copytree(template, stage)
    if entries:
        _write_db(stage, entries)
    else:
        for f in (stage / 'Stalker2/Content').glob(f'{DB_STEM}.*'):
            f.unlink()
    if cooked:
        _add_cooked(stage, cooked)
    for rel, text in patches.items():
        f = stage / 'Stalker2/Content/GameLite' / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding='ascii')

    mod_dir = f'Stalker2/Mods/{MOD}'
    paks = f'{mod_dir}/Content/Paks/Windows'
    shutil.rmtree(out, ignore_errors=True)
    parts = {
        # container: (legacy asset dir, pak payload dir, pak mount point)
        'OverrideContent': ('Stalker2/Content', 'Stalker2/Content/GameLite', '../../../Stalker2/Content/GameLite/'),
        'NewContent': (f'{mod_dir}/Content', mod_dir, f'../../../{mod_dir}/'),
    }
    for part, (assets, pak_src, mount) in parts.items():
        legacy = Path(tmp) / f'legacy-{part}'
        shutil.rmtree(legacy, ignore_errors=True)
        shutil.copytree(stage / assets, legacy / assets, ignore=shutil.ignore_patterns('*.cfg'))
        root = out / 'Windows' / part / 'Windows'
        dst = root / paks
        dst.mkdir(parents=True)
        # the container id is hashed from the file stem; Zone Kit uses "<Mod>Stalker2-Windows" for both parts
        base = Path(tmp) / f'{MOD}Stalker2-Windows.utoc'
        # Match Zone Kit output (needs retoc with tools/retoc-zonekit.patch):
        # - the utoc mount point is the asset folder itself;
        # - OverrideContent packages live under /Game/ on disk but are named /<Mod>/...; the game finds them by file
        #   path, so the container header must redirect /Game/<name> to /<Mod>/<name>.
        env = dict(os.environ, RETOC_TOC_MOUNT_POINT=f'../../../{assets}/')
        if assets == 'Stalker2/Content':
            stems = sorted(p.stem for p in (legacy / assets).glob('*.uasset'))
            stems.sort(key=lambda n: not n.startswith('__ModKitWwiseCookAnchor'))  # Zone Kit order: anchor first
            env['RETOC_PACKAGE_REDIRECTS'] = ';'.join(f'/Game/{n}=/{MOD}/{n}' for n in stems)
        subprocess.run([retoc, 'to-zen', '--version', 'UE5_5', str(legacy), str(base)], check=True,
                       stdout=subprocess.DEVNULL, env=env)
        name = f'{MOD}Stalker2-Windows-{part}'
        for ext in ('utoc', 'ucas'):
            shutil.move(str(base.with_suffix(f'.{ext}')), dst / f'{name}.{ext}')
        base.with_suffix('.pak').unlink()
        pak_dir = Path(tmp) / f'pak-{part}'
        shutil.rmtree(pak_dir, ignore_errors=True)
        pak_dir.mkdir()
        listed = []
        # pak payload: loose files (uplugin, AssetRegistry.bin, cfg patches); cooked assets live in the utoc
        (pak_dir / pak_src).mkdir(parents=True)
        for f in sorted((stage / pak_src).rglob('*')) if (stage / pak_src).exists() else []:
            if f.is_file() and f.suffix not in ('.uasset', '.uexp'):
                rel = f.relative_to(stage / pak_src)
                (pak_dir / pak_src / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(f, pak_dir / pak_src / rel)
                listed.append(f'{pak_src}/{rel}')
        subprocess.run([repak, 'pack', '-q', '--version', 'V11', '--mount-point', mount,
                        str(pak_dir / pak_src), str(dst / f'{name}.pak')], check=True)
        assets_listed = [str(p.relative_to(legacy)) for p in sorted(legacy.rglob('*')) if p.is_file()]
        _manifest(root / 'Manifest_UFSFiles_Win64.txt', assets_listed + listed + [f'{paks}/{name}.pak'])
    return out
